"""Generate bounded C# partial catalog methods from preserved catalog rows."""
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[1]
def generate(output):
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    rows=[]
    for source in sorted((ROOT/'Hazzure/catalog-data').glob('schema-skins-*.json')):
        rows.extend(json.loads(source.read_text(encoding='utf-8')))
    if not rows:raise ValueError('Missing catalog source snapshots')
    names=[]
    for start in range(0,len(rows),500):
        name=f'AddPart{start//500:03d}';names.append(name)
        lines=['// Generated by tools/generate_schema_skin_catalog.py.','using System.Collections.Generic;',
               'namespace ZyonEsp { static partial class SchemaSkinCatalog {',
               f'static void {name}(List<SkinEntry> result,HashSet<string> seen) {{']
        for definition,kit,label in rows[start:start+500]:
            lines.append(f'Add(result,seen,{definition},{kit},{json.dumps(label,ensure_ascii=True)});')
        lines+=['}','} }']
        (output/f'SchemaSkinCatalog.Part{start//500:03d}.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    lines=['// Generated from preserved local catalog rows.','using System.Collections.Generic;',
           'namespace ZyonEsp { static partial class SchemaSkinCatalog {',
           'public static SkinEntry[] Merge(SkinEntry[] original) {',
           'var result=new List<SkinEntry>(original);var seen=new HashSet<string>();',
           'foreach(var entry in original)seen.Add(entry.DefIndex+":"+entry.Kit);']
    lines += [f'{name}(result,seen);' for name in names]
    lines+=['return result.ToArray();}',
            'static void Add(List<SkinEntry> result,HashSet<string> seen,int def,int kit,string name) {',
            'if(seen.Add(def+":"+kit))result.Add(new SkinEntry(name,def,kit,0,.1f));','}','} }']
    (output/'SchemaSkinCatalog.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    return len(rows)
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,default=ROOT/'Hazzure')
    print('Catalog rows:',generate(parser.parse_args().output))
